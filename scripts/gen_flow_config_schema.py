def compute() -> dict:
    """Build the schema object (insertion order is property order)."""
    defaults = _default_leaves(flowctl.get_default_config())
    table = _build_table()
    _assert_unique_paths(table)

    schema: dict[str, Any] = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://flow-next.dev/schema/flow-config.schema.json",
        "title": "flow-next .flow/config.json",
        "description": DESCRIPTIONS["<root>"],
        "type": "object",
        "additionalProperties": False,
        "properties": {},
    }

    defaulted: set[str] = set()
    for path, spec in table:
        if path not in DESCRIPTIONS:
            raise AssertionError(f"missing description for TABLE path {path!r}")
        parts = path.split(".")
        parent_props = schema["properties"]
        for part in parts[:-1]:
            if part not in parent_props:
                raise AssertionError(
                    f"parent missing for {path!r} (need {part!r} first)"
                )
            parent_props = parent_props[part]["properties"]
        key = parts[-1]

        if spec.get("kind") == "object":
            node: dict[str, Any] = {
                "description": DESCRIPTIONS[path],
                # nullable: validator-accepted whole-block clear paths persist
                # null (e.g. `config set models null`) and must stay valid.
                "type": ["object", "null"] if spec.get("nullable") else "object",
                "additionalProperties": bool(spec["open"]),
                "properties": {},
            }
        else:
            node = {"description": DESCRIPTIONS[path]}
            node.update(spec)
            if path in defaults:
                node["default"] = defaults[path]
                defaulted.add(path)

        parent_props[key] = node

    if defaulted != set(defaults):
        missing = sorted(set(defaults) - defaulted)
        extra = sorted(defaulted - set(defaults))
        raise AssertionError(
            "TABLE leaf defaults diverge from get_default_config() leaves: "
            f"missing_defaults={missing} unexpected_defaults={extra}"
        )
    return schema


def render() -> str:
    """Deterministic JSON text (exactly one trailing newline)."""
    return (
        json.dumps(
            compute(),
            indent=2,
            ensure_ascii=True,
            separators=(",", ": "),
        )
        + "\n"
    )


def main() -> int:
    rendered = render()
    if "--check" in sys.argv[1:]:
        on_disk = OUT.read_bytes() if OUT.exists() else b""
        if on_disk != rendered.encode("utf-8"):
            print(
                "flow-config.schema.json is stale; "
                "run scripts/gen_flow_config_schema.py",
                file=sys.stderr,
            )
            return 1
        print("flow-config.schema.json is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(rendered.encode("utf-8"))
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


