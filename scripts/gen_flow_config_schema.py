def _default_leaves(obj: Any, prefix: str = "") -> dict[str, Any]:
    """Walk get_default_config() leaves (empty dict/list are leaves)."""
    out: dict[str, Any] = {}
    if isinstance(obj, dict):
        if not obj:
            out[prefix] = obj
            return out
        for key, val in obj.items():
            path = f"{prefix}.{key}" if prefix else key
            out.update(_default_leaves(val, path))
        return out
    out[prefix] = obj
    return out


def _review_backend_fragment() -> dict:
    model_backends = sorted(
        b for b, r in flowctl.BACKEND_REGISTRY.items() if r.get("models")
    )
    effort_backends = sorted(
        b
        for b, r in flowctl.BACKEND_REGISTRY.items()
        if r.get("models") and r.get("efforts")
    )
    model_only = sorted(set(model_backends) - set(effort_backends))
    # One pattern branch PER effort backend, each with that backend's own
    # effort set - a union alternation would accept e.g. copilot:<m>:none,
    # which flowctl rejects at parse time. Backend names are re.escape()d so
    # a future name carrying a regex metachar cannot corrupt the pattern.
    effort_branches = [
        {
            "type": "string",
            "pattern": (
                # Model component OPTIONAL: BackendSpec.parse accepts
                # effort-only (`codex::high`) and bare-colon (`codex:`)
                # shapes - runtime-valid configs must not fail editors.
                f"^{re.escape(b)}:[^:\\s]*"
                f"(:({'|'.join(sorted(flowctl.BACKEND_REGISTRY[b]['efforts']))})?)?$"
            ),
        }
        for b in effort_backends
    ]
    only_alt = "|".join(re.escape(b) for b in model_only)
    return {
        "anyOf": [
            {"type": "null"},
            {"enum": list(flowctl.VALID_BACKENDS)},
            # Degenerate-but-runtime-valid: a bare backend with ONE trailing
            # colon (`rp:`) parses to the bare backend.
            {
                "type": "string",
                "pattern": "^(" + "|".join(re.escape(b) for b in sorted(flowctl.VALID_BACKENDS)) + "):{1,2}$",
            },
            *effort_branches,
            {"type": "string", "pattern": f"^({only_alt}):[^:\\s]*:?$"},  # model-only: optional trailing empty effort colon
        ],
    }


def _models_roles_fragment() -> dict:
    role_pat = "^(" + "|".join(flowctl.MODEL_ROLES) + ")$"
    backend_pat = "^(" + "|".join(flowctl.MODEL_ROLE_BACKENDS) + ")$"
    return {
        # roles-level null is also a validator-accepted clear path.
        "type": ["object", "null"],
        "patternProperties": {
            role_pat: {
                # `config set models.roles.<role> null` is a supported clear
                # path (_validate_models_config_key accepts + persists null;
                # nested reads treat it as absent) - null must stay valid.
                "type": ["object", "null"],
                "description": DESCRIPTIONS["models.roles.<role>"],
                "patternProperties": {
                    backend_pat: {
                        # A pin is `model[:effort]`; the supported clear path
                        # (`config set ... null` / empty value) PERSISTS null
                        # or "" and get_role_map_pin treats both as no-pin -
                        # cleared configs must stay editor-valid.
                        "anyOf": [
                            {"type": "null"},
                            {"enum": [""]},
                            {
                                "type": "string",
                                "pattern": "^[^:\\s]+(:[^:\\s]+)?$",
                            },
                        ],
                        "description": DESCRIPTIONS[
                            "models.roles.<role>.<backend>"
                        ],
                    },
                },
                "additionalProperties": False,
            },
        },
        "additionalProperties": False,
    }


def _scope_resolved_at_fragment() -> dict:
    """SCOPES keys include dots - bake as a leaf so path-split stays safe."""
    props: dict[str, Any] = {}
    for scope in SCOPES:
        props[scope] = {
            "type": "string",
            "description": (
                f"ISO timestamp of the last successful {scope} resolution."
            ),
        }
    return {
        "type": "object",
        "additionalProperties": False,
        "properties": props,
    }


